int ter_ecu_config_pack(
    uint8_t *dst_p,
    const struct ter_ecu_config_t *src_p,
    size_t size)
{
    uint16_t flap_l_offset;
    uint16_t flap_r_offset;
    uint16_t regen_max_current;
    uint32_t trq_kd;
    uint32_t trq_ki;
    uint32_t trq_kp;

    if (size < 8u) {
        return (-EINVAL);
    }

    memset(&dst_p[0], 0, 8);

    dst_p[0] |= pack_left_shift_u8(src_p->entry, 0u, 0xffu);

    switch (src_p->entry) {

    case 0:
        dst_p[1] |= pack_left_shift_u8(src_p->scs_enable, 0u, 0x01u);
        break;

    case 1:
        dst_p[1] |= pack_left_shift_u8(src_p->r2_d_brake, 0u, 0xffu);
        break;

    case 2:
        dst_p[1] |= pack_left_shift_u8(src_p->limiter, 0u, 0xffu);
        break;

    case 3:
        dst_p[1] |= pack_left_shift_u8(src_p->driving_mode, 0u, 0xffu);
        break;

    case 4:
        dst_p[1] |= pack_left_shift_u8(src_p->traction_control, 0u, 0xffu);
        break;

    case 5:
        trq_kp = (uint32_t)src_p->trq_kp;
        dst_p[1] |= pack_left_shift_u32(trq_kp, 0u, 0xffu);
        dst_p[2] |= pack_right_shift_u32(trq_kp, 8u, 0xffu);
        dst_p[3] |= pack_right_shift_u32(trq_kp, 16u, 0xffu);
        dst_p[4] |= pack_right_shift_u32(trq_kp, 24u, 0xffu);
        break;

    case 6:
        trq_ki = (uint32_t)src_p->trq_ki;
        dst_p[1] |= pack_left_shift_u32(trq_ki, 0u, 0xffu);
        dst_p[2] |= pack_right_shift_u32(trq_ki, 8u, 0xffu);
        dst_p[3] |= pack_right_shift_u32(trq_ki, 16u, 0xffu);
        dst_p[4] |= pack_right_shift_u32(trq_ki, 24u, 0xffu);
        break;

    case 7:
        trq_kd = (uint32_t)src_p->trq_kd;
        dst_p[1] |= pack_left_shift_u32(trq_kd, 0u, 0xffu);
        dst_p[2] |= pack_right_shift_u32(trq_kd, 8u, 0xffu);
        dst_p[3] |= pack_right_shift_u32(trq_kd, 16u, 0xffu);
        dst_p[4] |= pack_right_shift_u32(trq_kd, 24u, 0xffu);
        break;

    case 8:
        dst_p[1] |= pack_left_shift_u8(src_p->trq_limit, 0u, 0xffu);
        break;

    case 9:
        dst_p[1] |= pack_left_shift_u8(src_p->eeprom, 0u, 0xffu);
        break;

    case 10:
        flap_l_offset = (uint16_t)src_p->flap_l_offset;
        dst_p[1] |= pack_left_shift_u16(flap_l_offset, 0u, 0xffu);
        dst_p[2] |= pack_right_shift_u16(flap_l_offset, 8u, 0xffu);
        break;

    case 11:
        flap_r_offset = (uint16_t)src_p->flap_r_offset;
        dst_p[1] |= pack_left_shift_u16(flap_r_offset, 0u, 0xffu);
        dst_p[2] |= pack_right_shift_u16(flap_r_offset, 8u, 0xffu);
        break;

    case 12:
        dst_p[1] |= pack_left_shift_u8(src_p->flap_l_reverse, 0u, 0xffu);
        break;

    case 13:
        dst_p[1] |= pack_left_shift_u8(src_p->flap_r_reverse, 0u, 0xffu);
        break;

    case 14:
        dst_p[1] |= pack_left_shift_u8(src_p->flap_enable, 0u, 0xffu);
        break;

    case 15:
        dst_p[1] |= pack_left_shift_u8(src_p->flap_pedal_setpoint, 0u, 0xffu);
        break;

    case 16:
        dst_p[1] |= pack_left_shift_u8(src_p->regen_enable, 0u, 0xffu);
        break;

    case 17:
        dst_p[1] |= pack_left_shift_u8(src_p->regen_max_trq, 0u, 0xffu);
        break;

    case 18:
        dst_p[1] |= pack_left_shift_u16(src_p->regen_max_cell_volt, 0u, 0xffu);
        dst_p[2] |= pack_right_shift_u16(src_p->regen_max_cell_volt, 8u, 0xffu);
        break;

    case 19:
        dst_p[1] |= pack_left_shift_u8(src_p->regen_max_cell_temp, 0u, 0xffu);
        break;

    case 20:
        regen_max_current = (uint16_t)src_p->regen_max_current;
        dst_p[1] |= pack_left_shift_u16(regen_max_current, 0u, 0xffu);
        dst_p[2] |= pack_right_shift_u16(regen_max_current, 8u, 0xffu);
        break;

    case 21:
        dst_p[1] |= pack_left_shift_u8(src_p->regen_thr_speed, 0u, 0xffu);
        break;

    case 22:
        dst_p[1] |= pack_left_shift_u16(src_p->regen_thr_rpm, 0u, 0xffu);
        dst_p[2] |= pack_right_shift_u16(src_p->regen_thr_rpm, 8u, 0xffu);
        break;

    case 23:
        dst_p[1] |= pack_left_shift_u8(src_p->regen_trq_slope, 0u, 0xffu);
        break;

    case 24:
        dst_p[1] |= pack_left_shift_u8(src_p->regen_mode, 0u, 0xffu);
        break;

    case 25:
        dst_p[1] |= pack_left_shift_u8(src_p->regen_max_positive_trq_thr, 0u, 0xffu);
        break;

    case 26:
        dst_p[1] |= pack_left_shift_u8(src_p->dv_mission_req, 0u, 0xffu);
        break;

    default:
        break;
    }

    return (8);
}

